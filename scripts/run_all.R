#!/usr/bin/env Rscript
args <- commandArgs(trailingOnly=FALSE)
script <- sub("^--file=", "", args[grepl("^--file=",args)])
if(length(script)) setwd(dirname(dirname(normalizePath(script))))
if(dir.exists(".R-library")) .libPaths(c(normalizePath(".R-library"),.libPaths()))
for(nm in c("core","geometry","graphics","exact_geometry","fit")) source(file.path("R",paste0(nm,".R")))
manuscript_dir <- if(file.exists("manuscript/manuscript.tex")) "manuscript" else "."
for(d in c("results","figures",file.path(manuscript_dir,"generated"),file.path(manuscript_dir,"figures"))) dir.create(d,showWarnings=FALSE,recursive=TRUE)
write_json <- function(x,path) jsonlite::write_json(x,path,auto_unbox=TRUE,pretty=TRUE,digits=17,null="null",na="null")
started <- proc.time()[[3]]
g <- run_geometry()
write_json(g,"results/geometry.json")
write.csv(g$local_radius$table,"results/local_radii.csv",row.names=FALSE)
exact <- run_exact_geometry()
write_json(exact,"results/exact_geometry.json")
make_triangle_figure(g); make_radius_figure(g)
X <- as.matrix(read.csv("data/fixed_budget.csv"))
fixed <- fit_fixed(X)
joint_data <- fit_joint_data()
write.csv(joint_data,"data/joint_budget.csv",row.names=FALSE)
joint <- fit_joint(joint_data)
sdp <- fit_fixed_density_sdp()
write_json(fixed,"results/fixed_budget.json"); saveRDS(fixed,"results/fixed_budget.rds")
write_json(joint,"results/joint_budget.json"); saveRDS(joint,"results/joint_budget.rds")
write_json(sdp,"results/fixed_density_sdp.json")
records <- c(fixed$steps,joint$steps)
tab <- do.call(rbind,lapply(seq_along(records),function(i) {
  z<-records[[i]]
  data.frame(check=if(i<=3)"fixed" else "joint",step=z$step,solver_status=z$solver_status,
    log_likelihood=z$log_likelihood_per_observation,likelihood_gain=z$log_likelihood_increase_per_observation,
    auxiliary_gain=z$EM_auxiliary_increase_per_observation,proximal_penalty=z$proximal_penalty,
    exact_minimum_slack=z$exact_checks$minimum,maximum_inner_violation=z$inner_checks$maximum_violation,
    retained_fraction=z$retained_step_fraction)
}))
write.csv(tab,"results/fitting_summary.csv",row.names=FALSE)
make_fit_figure(tab,fixed$initial_log_likelihood_per_observation)
rows <- vapply(seq_len(nrow(tab)),function(i) sprintf("%s & %.8f & %.8f & %.8f \\\\",
  if(i<=3) paste0("Fixed budget, step ",i) else "Joint budget, one step",
  tab$likelihood_gain[i],tab$auxiliary_gain[i],tab$proximal_penalty[i]),"")
writeLines(c("% Generated by scripts/run_all.R; values from the native R runs.",
  r"(\begin{tabular}{lrrr})", r"(\toprule)",
  r"(Check & Log-likelihood gain & Auxiliary gain & Proximal penalty\\)",
  r"(\midrule)", rows, r"(\bottomrule)", r"(\end{tabular})"),
  file.path(manuscript_dir,"generated/fitting_table.tex"))
fmt_matrix <- function(A) sprintf("\\begin{pmatrix}%.7f&%.7f\\\\%.7f&%.7f\\end{pmatrix}",A[1,1],A[1,2],A[2,1],A[2,2])
tex_sci <- function(x) { e<-floor(log10(abs(x))); sprintf("%.2f\\times 10^{%d}",x/10^e,e) }
matmin <- min(vapply(fixed$steps,function(s)min(unlist(s$exact_checks$minima[c("lambda_psd","first_lifted_matrix","first_actual_matrix","second_matrix")])),0))
macros <- c(sprintf("\\newcommand{\\RFixedWeights}{(%s)}",paste(sprintf("%.7f",softmax(fixed$final_lift$alpha)),collapse=",")),
  paste0("\\newcommand{\\RFixedCovariance}{",fmt_matrix(fixed$final_shared_covariance),"}"),
  paste0("\\newcommand{\\RJointCovariance}{",fmt_matrix(joint$final_shared_covariance),"}"),
  sprintf("\\newcommand{\\RFixedMatrixSlack}{%s}",tex_sci(matmin)),
  sprintf("\\newcommand{\\RJointViolation}{%s}",tex_sci(joint$steps[[1]]$inner_checks$maximum_violation)),
  sprintf("\\newcommand{\\RCVXRVersion}{%s}",packageVersion("CVXR")),
  sprintf("\\newcommand{\\RClarabelVersion}{%s}",packageVersion("clarabel")),
  sprintf("\\newcommand{\\RVersion}{%s}",getRversion()))
writeLines(c("% Generated native R output macros.",macros),file.path(manuscript_dir,"generated/r_results.tex"))
if(manuscript_dir != ".") for(ext in c("pdf","png")) file.copy(paste0("figures/triangle_modes.",ext),file.path(manuscript_dir,paste0("figures/triangle_modes.",ext)),overwrite=TRUE)
write_json(g$triangle$mode_search,"figures/triangle_mode_coordinates.json")
if(manuscript_dir != ".") file.copy("figures/triangle_mode_coordinates.json",file.path(manuscript_dir,"figures/triangle_mode_coordinates.json"),overwrite=TRUE)
writeLines(sub("[[:blank:]]+$","",capture.output(sessionInfo())),"results/sessionInfo.txt")
versions<-vapply(c("CVXR","clarabel","jsonlite","gmp","Matrix","S7"),function(p)as.character(packageVersion(p)),"")
write_json(list(R=as.character(getRversion()),packages=as.list(versions),
  elapsed_seconds=proc.time()[[3]]-started,scope="Three fixed-budget steps and one joint-budget step; no convergence or global optimality diagnosis."),"results/run_metadata.json")
cat("Completed native R computations and graphics.\n")
print(tab)
